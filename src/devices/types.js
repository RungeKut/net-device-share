// Типы разделяемых устройств и правила их идентификации.
//
// Раньше устройство опознавалось по busid — это годилось, пока типов был
// ровно один. Теперь идентификатор составной: "<тип>:<локальный ключ>",
// например "usb:1-4", "com:COM3", "net:{8A2C...}". Тип в самом ключе
// избавляет от параллельных пространств имён и делает вид записи
// самообъясняющим в журналах и в протоколе.

export const DEVICE_TYPES = {
  usb: {
    id: 'usb',
    title: 'USB-устройство',
    plural: 'USB-устройства',
    icon: '🔌',
    // Полноценный проброс: устройство появляется в «Диспетчере устройств».
    transport: 'usbip',
  },
  com: {
    id: 'com',
    title: 'Последовательный порт',
    plural: 'Последовательные порты (COM)',
    icon: '🔗',
    transport: 'none',
  },
  lpt: {
    id: 'lpt',
    title: 'Параллельный порт',
    plural: 'Параллельные порты (LPT)',
    icon: '🖨',
    transport: 'none',
  },
  net: {
    id: 'net',
    title: 'Сетевой интерфейс',
    plural: 'Сетевые интерфейсы',
    icon: '🌐',
    // Карта владельца становится сетевым адаптером занявшего: TAP-адаптер
    // у обоих, мост Windows у владельца (см. core/netShare.js). Пробросить
    // можно не всякую карту — какую нельзя и почему, решает владелец, и
    // такая карта остаётся в режиме брони.
    transport: process.platform === 'win32' ? 'tap' : 'none',
  },
};

/**
 * Пояснение для типов без проброса данных.
 *
 * Их занятость учитывается по-настоящему — каталог, аренда, запросы, группы
 * работают одинаково для всех типов. Не работает именно передача данных по
 * сети: для COM нужен драйвер виртуального порта у клиента, у LPT сетевого
 * стандарта не существует. Сетевая карта пробрасывается, но не любая —
 * Wi-Fi, программные адаптеры и карта, через которую работает само
 * приложение, остаются в режиме брони. Такие устройства бронируются, а
 * подключаются к ним физически.
 */
export const RESERVATION_NOTE =
  'Только бронирование: приложение учитывает, кто занял устройство, но данные по сети не пробрасывает.';

export function typeInfo(type) {
  return DEVICE_TYPES[type] || {
    id: type,
    title: 'Устройство',
    plural: 'Устройства',
    icon: '❓',
    transport: 'none',
  };
}

export function hasTransport(type) {
  return typeInfo(type).transport !== 'none';
}

/** "usb" + "1-4" → "usb:1-4" */
export function makeDeviceId(type, key) {
  return `${type}:${key}`;
}

/** "usb:1-4" → { type: "usb", key: "1-4" } */
export function parseDeviceId(deviceId) {
  const s = String(deviceId || '');
  const at = s.indexOf(':');
  if (at < 0) {
    // Записи без префикса остались от первой версии, где типы не различались.
    return { type: 'usb', key: s };
  }
  return { type: s.slice(0, at), key: s.slice(at + 1) };
}

/** Глобальный ключ: уникален в пределах всей сети. */
export function globalId(nodeId, deviceId) {
  return `${nodeId}|${deviceId}`;
}
