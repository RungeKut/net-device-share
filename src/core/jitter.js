// Разброс периодических таймеров. Узлы, поднятые вместе (дали питание разом,
// запустили пачкой скриптом, перезапустились обновлением), иначе ходили бы в
// сеть синхронно — анонсы, опросы, продление аренд — и нагрузка приходила бы
// волнами, а не ровно. Доля ограничена половиной: больший разброс уже меняет
// смысл самого периода.
export function jittered(ms, fraction, random = Math.random) {
  const f = Math.min(0.5, Math.max(0, Number(fraction) || 0));
  if (!f) return ms;
  return Math.max(1, Math.round(ms * (1 - f + 2 * f * random())));
}
